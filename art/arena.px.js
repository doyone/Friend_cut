// 판 그리기: 각도마다 새로 칠해서 칸 경계가 안 뭉개진다 (독박 룰렛의 룰렛판과 같은 방식). theta = 시계 방향으로 돌린 각도
function drawArenaWheel(c, theta, { R, rim, hub, bulbs }) {
  const cx = c.w / 2;
  const cy = c.h / 2;
  const N = WSEGS.length;
  const seg = TAU3 / N;
  for (let y = 0; y < c.h; y++) {
    for (let x = 0; x < c.w; x++) {
      const dx = x + 0.5 - cx;
      const dy = y + 0.5 - cy;
      const r = Math.hypot(dx, dy);
      if (r > R) continue;
      const lit = r ? (-dx - dy) / (r * Math.SQRT2) : 1;
      if (r > R - rim) { c.px(x, y, lit > 0.25 ? "y" : lit > -0.5 ? "Y" : "D"); continue; }
      if (r > R - rim - 1) { c.px(x, y, "k"); continue; }
      if (r < hub) { c.px(x, y, r < hub * 0.4 ? "k" : lit > 0 ? "y" : "Y"); continue; }
      let a = (Math.atan2(dx, -dy) - theta) % TAU3;
      if (a < 0) a += TAU3;
      const u = a / seg;
      const i = Math.round(u) % N;
      if ((0.5 - Math.abs(u - Math.round(u))) * seg * r < 0.5) { c.px(x, y, "k"); continue; }
      const [hi, lo] = WSEGS[i];
      c.px(x, y, r < (R - rim) * 0.42 ? lo : hi);
    }
  }
  for (let j = 0; j < bulbs; j++) { // 테의 불빛: 흰 것 · 주황 것 번갈아
    const ang = theta + ((j + 0.5) / bulbs) * TAU3;
    const rr = R - rim / 2;
    c.px(Math.floor(cx + rr * Math.sin(ang)), Math.floor(cy - rr * Math.cos(ang)), j % 2 ? "w" : "o");
  }
  for (let i = 0; i < N; i++) {
    const ang = theta + i * seg;
    const rr = (R - rim) * 0.7;
    const [w, h] = wiSize(WSEGS[i][2]);
    c.stamp(`_wi_${WSEGS[i][2]}`, Math.round(cx + rr * Math.sin(ang) - w / 2), Math.round(cy - rr * Math.cos(ang) - h / 2));
  }
}
